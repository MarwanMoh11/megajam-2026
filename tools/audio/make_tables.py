"""Writes the C++ voice table and the tables in docs/AUDIO_SCRIPT.md from manifest.py.

  python tools/audio/make_tables.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import manifest as M  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
INL = os.path.join(ROOT, "Reel", "Source", "Reel", "Take", "TakeAudioLines.inl")
DOC = os.path.join(ROOT, "docs", "AUDIO_SCRIPT.md")
BEGIN, END = "<!-- tables: begin (tools/audio/make_tables.py writes this part) -->", "<!-- tables: end -->"


def c_str(s):
    assert all(ord(ch) < 128 for ch in s), f"non-ASCII in {s!r}"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_inl():
    out = ["// Generated by tools/audio/make_tables.py from tools/audio/manifest.py. Do not edit by hand.",
           "// TAKE_AUDIO_ROW(id, speaker, subtitle, key): key is \"SPEAKER|line the game flashes\" or \"@event\".", ""]
    for (lid, speaker, text, key, _event, _say) in M.LINES:
        out.append(f"TAKE_AUDIO_ROW({c_str(lid)}, {c_str(speaker)}, {c_str(text)}, {c_str(key)})")
    with open(INL, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def est_seconds(text):
    return max(0.6, round(len(text.split()) / 2.6 + 0.3, 1))   # about 2.6 words a second


def md(s):
    return s.replace("|", "\\|")


def tables():
    t = ["### Voices", "", "| Character | ElevenLabs voice | Why |", "|---|---|---|"]
    for who, v in M.VOICES.items():
        t.append(f"| {who} | {v['voice']} (`{v['voice_id']}`) | {v['why']} |")
    t += ["", f"Model `{M.TTS_MODEL}`. Earpiece lines ({', '.join(sorted(M.EARPIECE))}) are band-passed like a radio "
          "in `process.py`.", "", "### Lines", "",
          "| File | Speaker | Subtitle (and what is said) | Event | How the game asks | Length |", "|---|---|---|---|---|---|"]
    for (lid, speaker, text, key, event, say) in M.LINES:
        shown = md(text) + (f" (said: *{md(say)}*)" if say else "")
        if key.startswith("@"):
            how = f"`{key}`"
        elif key.split("|", 1)[1] == text:
            how = "its words"
        else:
            how = "variant of: " + md(key.split("|", 1)[1])
        t.append(f"| `{lid}` | {speaker} | {shown} | {md(event)} | {how} | ~{est_seconds(say or text)} s |")
    t += ["", "### Sound effects", "", "| File | Event | Length | Loop | Prompt |", "|---|---|---|---|---|"]
    for (sid, event, secs, prompt, loop) in M.SFX:
        t.append(f"| `{sid}` | {md(event)} | {secs} s | {'yes' if loop else ''} | {md(prompt)} |")
    t += ["", "### The band and the score", "", "| File | Event | Shipped length | Source | Prompt |", "|---|---|---|---|---|"]
    for (mid, event, bars, gen_s, kind, prompt) in M.MUSIC:
        length = f"{bars} bars ({bars * M.BEATS_PER_BAR * 60 // M.TEMPO_BPM} s)" if bars else "one-shot, trimmed"
        src = "ElevenLabs Music" if kind == "music" else "ElevenLabs SFX"
        t.append(f"| `{mid}` | {md(event)} | {length} | {src}, {gen_s} s generated | {md(prompt)} |")
    t += ["", "### Loudness", "", "| Prefix | Integrated LUFS |", "|---|---|"]
    for p, l in M.LOUDNESS.items():
        t.append(f"| `{p}` | {l} |")
    t.append(f"\nPeaks at most {M.PEAK_DBFS} dBFS.")
    return "\n".join(t)


def write_doc():
    with open(DOC, encoding="utf-8") as f:
        doc = f.read()
    a, b = doc.index(BEGIN) + len(BEGIN), doc.index(END)
    with open(DOC, "w", encoding="utf-8", newline="\n") as f:
        f.write(doc[:a] + "\n\n" + tables() + "\n\n" + doc[b:])


if __name__ == "__main__":
    write_inl()
    write_doc()
    print(f"{len(M.LINES)} lines, {len(M.SFX)} sound effects, {len(M.MUSIC)} music cues")
