"""Scene 5: Pendleton's lip sync, baked from his speech -> Reel/Source/Reel/Take/Script/Scene5Lipsync.inl.

Outside the editor (the audio venv), after scene5_audio.py made the voice:
  C:\\Jam\\venv-audio\\Scripts\\python.exe tools/script/scene5_lipsync.py
Re-run it whenever vo_s5_pendleton is re-voiced, then compile (a .inl body change: Live Coding is enough).

The dry voice (the raw MP3 put through the same trim and pause cap as scene5_audio.py, without the hall reverb, so
the timing matches the WAV the game plays) is cut into 30 fps frames. Two channels per frame, 0..255:
  Open  how far the jaw drops: the frame's loudness above the noise floor, fast attack, quick release, so each
        syllable opens and closes
  Wide  how wide the lips spread: the share of energy above 2.5 kHz (ee, s, t spread the lips; oo, o, m round them)
The C++ (AScene5Auditorium::StepMouth) reads them at the speech's play time.
"""
import os
import sys

import numpy as np

REPO = r"C:\Jam\megajam"
RAW = r"C:\Jam\Audio\script\s5\raw\vo_s5_pendleton.mp3"
WAV = r"C:\Jam\Audio\script\s5\vo_s5_pendleton.wav"
OUT = os.path.join(REPO, r"Reel\Source\Reel\Take\Script\Scene5Lipsync.inl")
FPS = 30
sys.path.insert(0, os.path.join(REPO, "tools", "audio"))


def main():
    import process as P
    from audio_io import decode_mp3, read_wav
    R = P.RATE
    x, rate = decode_mp3(RAW)
    x = P.mono(P.to_rate(x, rate))
    x = P.fade(P.cap_pauses(P.trim(x, -45, 0.02, 0.15)), 0.005, 0.04)
    hop = R // FPS
    n = len(x) // hop
    # loudness in the voice band (300 Hz - 3 kHz: vowels are loud there, consonants and closures dip)
    win2 = np.hanning(hop * 2)
    fq = np.fft.rfftfreq(hop * 2, 1.0 / R)
    band = (fq > 300) & (fq < 3000)
    db = np.zeros(n)
    for i in range(n):
        a = max(0, i * hop - hop // 2)
        seg = x[a:a + hop * 2]
        if len(seg) < hop * 2:
            seg = np.pad(seg, (0, hop * 2 - len(seg)))
        db[i] = 10 * np.log10(np.sum((np.abs(np.fft.rfft(seg * win2)) ** 2)[band]) + 1e-12)
    top = np.percentile(db, 95)
    level = np.clip((db - (top - 22.0)) / 22.0, 0.0, 1.0)
    # syllables: how far this frame stands above the quietest frame around it (+-120 ms)
    k = int(0.12 * FPS)
    floor_ = np.array([db[max(0, i - k):i + k + 1].min() for i in range(n)])
    syl = np.clip((db - floor_) / 12.0, 0.0, 1.0)
    open_ = level * (0.25 + 0.75 * syl)
    # fast attack, quick release (a mouth shuts between syllables)
    sm = np.zeros(n)
    acc = 0.0
    for i, v in enumerate(open_):
        acc = v if v > acc else acc + (v - acc) * 0.6
        sm[i] = acc
    # high-band share per frame
    win = np.hanning(hop * 2)
    wide = np.zeros(n)
    freqs = np.fft.rfftfreq(hop * 2, 1.0 / R)
    for i in range(n):
        seg = x[max(0, i * hop - hop // 2): max(0, i * hop - hop // 2) + hop * 2]
        if len(seg) < hop * 2:
            seg = np.pad(seg, (0, hop * 2 - len(seg)))
        sp = np.abs(np.fft.rfft(seg * win)) ** 2
        tot = np.sum(sp[(freqs > 80)]) + 1e-12
        wide[i] = np.sum(sp[freqs > 2500]) / tot
    wide = np.clip(wide / max(np.percentile(wide, 90), 1e-6), 0.0, 1.0)
    wide = np.convolve(wide, np.ones(3) / 3, mode="same")
    secs = len(x) / R
    try:
        wav, wr = read_wav(WAV)
        wav_secs = len(wav) / wr
    except Exception:
        wav_secs = secs
    o = (sm * 255).round().astype(int).tolist()
    w = (wide * 255).round().astype(int).tolist()

    def rows(v):
        return "\n".join("\t" + ", ".join(str(a) for a in v[i:i + 30]) + "," for i in range(0, len(v), 30))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/script/scene5_lipsync.py from vo_s5_pendleton (do not edit by hand).\n")
        f.write("// Pendleton's mouth, %d fps: Open (jaw) and Wide (lip spread), 0..255. Dry voice %.2f s, WAV %.2f s.\n"
                % (FPS, secs, wav_secs))
        f.write("#pragma once\n\nnamespace Scene5Lipsync\n{\n")
        f.write("\tconstexpr float Fps = %d.f;\n\tconstexpr float Seconds = %.3ff;\n" % (FPS, wav_secs))
        f.write("\tconstexpr int32 Frames = %d;\n" % n)
        f.write("\tstatic const uint8 Open[] = {\n%s\n\t};\n" % rows(o))
        f.write("\tstatic const uint8 Wide[] = {\n%s\n\t};\n}\n" % rows(w))
    talk = np.mean(sm > 0.15)
    print(f"lipsync: {n} frames, dry {secs:.2f} s, wav {wav_secs:.2f} s, open>0.15 in {talk:.0%} of frames -> {OUT}")


if __name__ == "__main__":
    main()
